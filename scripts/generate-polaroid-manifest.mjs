import { readdir, mkdir, writeFile } from "node:fs/promises";
import { extname, join } from "node:path";

const root = process.cwd();
const photoDirectory = join(root, "public", "polaroids");
const outputFile = join(root, "src", "content", "generatedPolaroids.ts");
const supported = new Set([".jpg", ".jpeg", ".png", ".webp"]);

await mkdir(photoDirectory, { recursive: true });
const files = (await readdir(photoDirectory, { withFileTypes: true }))
  .filter(
    (entry) =>
      entry.isFile() && supported.has(extname(entry.name).toLowerCase()),
  )
  .map((entry) => entry.name)
  .sort((first, second) => first.localeCompare(second));

const source = `// Generated by scripts/generate-polaroid-manifest.mjs. Do not edit manually.\nexport const GENERATED_POLAROID_FILES = ${JSON.stringify(files, null, 2)} as const;\n`;
await writeFile(outputFile, source, "utf8");
console.log(`Polaroid manifest: ${files.length} photo(s).`);
